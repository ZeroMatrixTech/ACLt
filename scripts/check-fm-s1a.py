VECTOR_PATH=ROOT/'tests/formal_migration/vectors.json'

def openssl(*args, **kwargs):
    return subprocess.run(['openssl',*map(str,args)],check=True,capture_output=True,timeout=30,**kwargs).stdout

def keypair(path):
    openssl('genpkey','-algorithm','RSA','-pkeyopt','rsa_keygen_bits:2048','-pkeyopt','rsa_keygen_pubexp:65537','-out',path)
    return openssl('pkey','-in',path,'-pubout','-outform','DER')

def record(der, role='REQUESTER', network=b'n'*32, deployment=b'd'*32):
    return dict(schema_version=1,encoding_profile_id=c.ENCODING,protocol_version=[0,5,0],network_id=network,deployment_id=deployment,principal_id=c.domain_hash(f.IDENTITY_TAG,der),key_id=hashlib.sha256(der).digest(),public_key_der=der,role=role,suite=f.SUITE,valid_from=1000,valid_until=10000,status='ACTIVE')

def value(operation='REQUEST'):
    return dict(operation=operation,count=2**64-1,offset=-(2**63),ratio=[-2,3],version=[1,0,0],enabled=True,label='é中',members=['a','z'])

def unsigned(rec, operation='REQUEST'):
    return dict(schema_version=1,encoding_profile_id=c.ENCODING,protocol_version=[0,5,0],network_id=rec['network_id'],deployment_id=rec['deployment_id'],suite=f.SUITE,principal_ref=f.principal_digest(rec),role=rec['role'],object_type='FM_TEST_VALUE',context=b'c'*32,nonce=b'x'*32,issued_at=2000,expires_at=3000,payload_ref=dict(id=f.IMPORT_ID,version=[1,0,0],digest=f.IMPORT_DIGEST),payload=c.encode(value(operation)))

def sign(unsigned_value,key):
    message=f.signing_input(unsigned_value)
    signature=openssl('dgst','-sha256','-sign',key,'-sigopt','rsa_padding_mode:pkcs1',input=message)
    return dict(unsigned_value,signature=signature)

def request(rec, env, now=2500):
    expected={k:env[k] for k in ('protocol_version','network_id','deployment_id','role','object_type','context','nonce')}
    expected['record_digest']=f.principal_digest(rec)
    return dict(record=rec,envelope=env,expected=expected,now=now)

def generate_vectors(tmp):
    key=tmp/'requester.pem';der=keypair(key);rec=record(der);u=unsigned(rec);env=sign(u,key);base=request(rec,env)
    rows=[]
    def add(label,kind,v,valid=True):
        raw=v if isinstance(v,bytes) else c.encode(v)
        row=dict(id=label,kind=kind,cbor_hex=raw.hex(),valid=valid)
        try:actual=f.inspect(kind,raw)
        except c.CodecError:
            if valid:raise
        else:
            assert valid,label
            row['expected']=actual
        rows.append(row)
    def bad(label,edit):
        v=copy.deepcopy(base);edit(v);add(label,'fm-verify',v,False)
    add('typed-boundaries','fm-value',value())
    add('requester-role','fm-role','REQUESTER')
    add('principal','fm-principal',rec)
    add('signing-input','fm-signing',u)
    add('envelope','fm-envelope',env)
    add('requester-valid','fm-verify',base)
    for role,op in [('PROVIDER','ACCEPT'),('PROVIDER','RESULT')]:
        pkey=tmp/(op+'.pem');r=record(keypair(pkey),role);add('provider-'+op.lower(),'fm-verify',request(r,sign(unsigned(r,op),pkey)))
    # Independent context/key rebinding positives: never pass by rejecting everything.
    for label,change in [('network',lambda r:r.update(network_id=b'j'*32)),('deployment',lambda r:r.update(deployment_id=b'e'*32)),('key',lambda r:None)]:
        r=copy.deepcopy(rec);k=key
        if label=='key':k=tmp/'rebound.pem';r=record(keypair(k))
        change(r);signed=sign(unsigned(r),k);add('rebound-'+label,'fm-verify',request(r,signed))
        old=request(r,signed);old['expected']['record_digest']=f.principal_digest(rec);add('rebound-'+label+'-stale-pin','fm-verify',old,False)
    for label,field in [('nonce','nonce'),('context','context')]:
        changed=copy.deepcopy(u);changed[field]=b'y'*32;new=sign(changed,key);add('resigned-'+label,'fm-verify',request(rec,new))
        stale=request(rec,new);stale['expected'][field]=u[field];add('resigned-'+label+'-old-context','fm-verify',stale,False)
    # Identical verification is intentionally idempotent; changing the challenge rejects replay.
    add('same-request-idempotent','fm-verify',base)
    for field in ('nonce','context','network_id','deployment_id'):
        bad('replay-wrong-'+field,lambda v,k=field:v['expected'].update({k:b'w'*32}))
    for field,replacement in [('schema_version',2),('protocol_version',[0,6,0]),('encoding_profile_id','unknown'),('suite','fm.rsa-pss'),('object_type','Receipt'),('role','ISSUER'),('principal_ref',b'q'*32),('network_id',b'q'*32),('deployment_id',b'q'*32),('nonce',b'q'*32),('context',b'q'*32),('signature',b'\0'*256),('issued_at',2100),('expires_at',3100)]:
        bad('envelope-wrong-'+field,lambda v,k=field,x=replacement:v['envelope'].update({k:x}))
    bad('signature-truncated',lambda v:v['envelope'].update(signature=env['signature'][:-1]))
    bad('signature-extended',lambda v:v['envelope'].update(signature=env['signature']+b'\0'))
    bad('changed-payload',lambda v:v['envelope'].update(payload=c.encode(dict(value(),count=7))))
    bad('untrusted-pin',lambda v:v['expected'].update(record_digest=b'q'*32))
    bad('wrong-known-role',lambda v:v['expected'].update(role='PROVIDER'))
    bad('principal-role-rebinding',lambda v:v['record'].update(role='PROVIDER'))
    bad('unknown-role',lambda v:v['record'].update(role='LOG_ISSUER'))
    bad('revoked-status',lambda v:v['record'].update(status='REVOKED'))
    for field,x in [('key_id',b'q'*32),('principal_id',b'q'*32),('valid_until',2500),('valid_from',2600)]:
        bad('record-'+field,lambda v,k=field,x=x:v['record'].update({k:x}))
    for label,now,valid in [('not-yet',1999,False),('issued-boundary',2000,True),('expiry-before',2999,True),('expiry-boundary',3000,False),('time-negative',-1,False)]:
        add(label,'fm-verify',request(rec,env,now),valid)
    for field,x in [('id','acl.schema.principal-ref@1'),('version',[2,0,0]),('digest',b'q'*32)]:
        bad('import-'+field,lambda v,k=field,x=x:v['envelope']['payload_ref'].update({k:x}))
    bad('unknown-envelope-field',lambda v:v['envelope'].update(extra=1))
    bad('unknown-record-field',lambda v:v['record'].update(extra=1))
    bad('unknown-trusted-context-field',lambda v:v['expected'].update(extra=1))
    r=copy.deepcopy(rec);r['public_key_der']=der[:-1]+b'\3';r['key_id']=hashlib.sha256(r['public_key_der']).digest();r['principal_id']=c.domain_hash(f.IDENTITY_TAG,r['public_key_der']);add('wrong-key-exponent','fm-principal',r,False)
    # Cryptographic failures after all structural checks: another valid key, bad padding/hash.
    other=tmp/'other.pem';keypair(other)
    for label,opts,k in [('wrong-signing-key',['-sha256','-sigopt','rsa_padding_mode:pkcs1'],other),('pss-padding',['-sha256','-sigopt','rsa_padding_mode:pss','-sigopt','rsa_pss_saltlen:32'],key),('wrong-hash',['-sha384','-sigopt','rsa_padding_mode:pkcs1'],key)]:
        e=dict(u,signature=openssl('dgst',*opts,'-sign',k,input=f.signing_input(u)));add(label,'fm-verify',request(rec,e),False)
    for label,edit in [('zero-denominator',lambda v:v.update(ratio=[1,0])),('unreduced',lambda v:v.update(ratio=[2,4])),('semver-short',lambda v:v.update(version=[1,0])),('enum-case',lambda v:v.update(operation='request')),('duplicate-set',lambda v:v.update(members=['a','a'])),('unordered-set',lambda v:v.update(members=['z','a'])),('uint-bool',lambda v:v.update(count=True)),('int-overflow',lambda v:v.update(offset=2**63)),('extra-field',lambda v:v.update(extra=1))]:
        v=value();edit(v);add(label,'fm-value',v,False)
    for label,raw in [('role-nonshortest',b'\x78\x09REQUESTER'),('role-trailing',c.encode('REQUESTER')+b'\0'),('role-non-nfc',b'\x63e\xcc\x81'),('role-invalid-utf8',b'\x61\xff'),('role-null',b'\xf6'),('role-float',bytes.fromhex('fa3f800000')),('role-bignum',bytes.fromhex('c24101')),('role-indefinite',b'\x7f\x69REQUESTER\xff'),('duplicate-map',bytes.fromhex('a2616101616102')),('unordered-map',bytes.fromhex('a2616201616102')),('integer-underflow',bytes.fromhex('3b8000000000000000')),('container-limit',bytes.fromhex('9bffffffffffffffff')),('depth-limit',b'\x81'*50+b'\0')]:
        add(label,'fm-role',raw,False)
    v=value();raw=c.encode(v);needle=c.encode('é中');non_nfc='e\u0301中'.encode();add('nested-non-nfc','fm-value',raw.replace(needle,c.head(3,len(non_nfc))+non_nfc),False)
    bad('payload-byte-limit',lambda v:v['envelope'].update(payload=b'x'*4097))
    # Self-selected issuer key is not a protocol Principal, even if it can sign.
    bad('issuer-role',lambda v:v['envelope'].update(role='ISSUER'))
    return rows

def compare(rows, binary, tmp, fresh=True):
    cases=[]
    def add(label, mode, wire, expected):cases.append((label,mode,wire,expected))
    for row in rows:
        want=row.get('expected') if row['valid'] else None
        try:actual=f.inspect(row['kind'],bytes.fromhex(row['cbor_hex']))
        except c.CodecError:actual=None
        assert actual==want,('Python golden',row['id'])
        add(row['id'],row['kind'],row['cbor_hex'],want)
        if row['valid'] and row['kind']!='fm-verify':
            source=json.dumps(want['schema_view'],ensure_ascii=True)
            assert f.from_view_json(row['kind'],source).hex()==row['cbor_hex']
            add('view-'+row['id'],'view-'+row['kind'],source,want)
    for kind,source in [('fm-role','"ISSUER"'),('fm-role','null'),('fm-value','{"count":"1","count":"2"}'),('fm-role','NaN')]:
        try:f.from_view_json(kind,source)
        except c.CodecError:pass
        else:raise AssertionError(source)
        add('invalid-JSON','view-'+kind,source,None)
    rng=random.Random(20261028)
    for i in range(80):
        v=value();v.update(count=rng.randrange(2**64),offset=rng.randrange(-2**63,2**63),ratio=[rng.randrange(-100,100),1],label=rng.choice(['','é','中','😀','가']))
        raw=c.encode(v);want=f.inspect('fm-value',raw);add('typed-grid-'+str(i),'fm-value',raw.hex(),want)
    if fresh:
        key=tmp/'fresh.pem';rec=record(keypair(key));u=unsigned(rec);py=f.signing_input(u)
        # Rust creates signing input from its own unvalidated raw parser and fields.
        output=json.loads(subprocess.run([str(binary)],input='fm-signing\t'+c.encode(u).hex()+'\n',text=True,capture_output=True,check=True,timeout=30).stdout)
        rust=bytes.fromhex(output['signing_input_hex']);assert rust==py
        sig_py=openssl('dgst','-sha256','-sign',key,'-sigopt','rsa_padding_mode:pkcs1',input=py)
        sig_rust=openssl('dgst','-sha256','-sign',key,'-sigopt','rsa_padding_mode:pkcs1',input=rust)
        assert sig_py==sig_rust
        req=request(rec,dict(u,signature=sig_rust));want=f.verify(req);add('fresh-independent-signing','fm-verify',c.encode(req).hex(),want)
    result=subprocess.run([str(binary)],input=''.join(m+'\t'+w+'\n' for _,m,w,_ in cases),capture_output=True,text=True,check=True,timeout=90)
    output=result.stdout.splitlines();assert len(output)==len(cases),(len(output),len(cases),result.stderr)
    for (label,mode,wire,want),line in zip(cases,output):
        got=json.loads(line)
        if want is None:assert set(got)=={'error'},('Rust negative',label,got)
        else:assert got==want,('Rust positive',label,got,want)
    return dict(cases=len(cases),frozen_vectors=len(rows),frozen_positive=sum(r['valid'] for r in rows),frozen_negative=sum(not r['valid'] for r in rows),rust_error_rejections=sum(w is None for _,_,_,w in cases),fresh_signing=fresh)

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--report',type=Path);p.add_argument('--freeze-vectors',action='store_true');args=p.parse_args()
    if args.report and args.report.exists():p.error('report exists')
    with tempfile.TemporaryDirectory(prefix='aclt-fm-check-') as name:
        tmp=Path(name);binary=tmp/'codec'
        subprocess.run([os.environ.get('RUSTC','rustc'),'--edition=2021','-D','warnings','-C','overflow-checks=yes','-O',str(ROOT/'tools/verification_profile/rust/main.rs'),'-o',str(binary)],check=True,timeout=90)
        if args.freeze_vectors:
            if VECTOR_PATH.exists():p.error('vectors already exist')
            rows=generate_vectors(tmp);VECTOR_PATH.write_text(json.dumps({'status':'CANDIDATE_TEST_ONLY','private_keys_included':False,'vectors':rows},ensure_ascii=False,indent=2)+'\n')
        else:rows=json.loads(VECTOR_PATH.read_text())['vectors']
        result=compare(rows,binary,tmp)
        result.update(status='PASS',scope='FM-S1a local codec and signature contract, not protocol admission',python=subprocess.check_output([sys.executable,'--version'],text=True).strip(),rustc=subprocess.check_output([os.environ.get('RUSTC','rustc'),'--version'],text=True).strip(),openssl=openssl('version').decode().strip(),source_sha256={n:hashlib.sha256((ROOT/n).read_bytes()).hexdigest() for n in ['tools/formal_migration/foundation.py','tools/verification_profile/codec.py','tools/verification_profile/rust/main.rs','tools/verification_profile/rust/profile.rs','tools/verification_profile/rust/registration.rs','tools/verification_profile/rust/audit_types.json','tools/verification_profile/rust/method_types.json','tools/verification_profile/rust/method_rules.rs','tools/verification_profile/rust/creation.rs','tools/verification_profile/rust/creation_types.json','tools/verification_profile/rust/selection.rs','tools/verification_profile/rust/selection_types.json','tools/verification_profile/rust/fm.rs','tools/verification_profile/rust/sha256.rs','tools/verification_profile/rust/nfc.rs','tools/verification_profile/rust/unicode_data.rs','scripts/check-fm-s1a.py','tests/formal_migration/vectors.json']})
    if args.report:args.report.parent.mkdir(parents=True,exist_ok=True);args.report.write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps({k:v for k,v in result.items() if k!='source_sha256'},indent=2))
if __name__=='__main__':main()
